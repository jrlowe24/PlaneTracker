/**
 * Generates src/geoidGrid.ts: EGM96 geoid undulation (meters above the WGS84
 * ellipsoid) on a 1° grid, sampled from egm96-universal (NGA's EGM96 15'
 * grid, public domain data). 181 × 361 int16 decimeters, base64.
 *
 *   pnpm --filter @windowseat/shared exec tsx scripts/generate-geoid.ts
 */
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { meanSeaLevel } from 'egm96-universal'

const rows = 181
const cols = 361
const values = new Int16Array(rows * cols)
for (let r = 0; r < rows; ++r) {
  const lat = -90 + r
  for (let c = 0; c < cols; ++c) {
    const lon = -180 + c
    values[r * cols + c] = Math.round(meanSeaLevel(lat, lon === 180 ? -180 : lon) * 10)
  }
}
const base64 = Buffer.from(values.buffer).toString('base64')
const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../src/geoidGrid.ts')
writeFileSync(
  out,
  `// Generated by scripts/generate-geoid.ts. Do not edit.
// EGM96 geoid undulation, 1° grid (lat −90…90 rows, lon −180…180 columns),
// int16 decimeters, little-endian, base64. Source data: NGA EGM96 (public domain).
export const GEOID_ROWS = ${rows}
export const GEOID_COLS = ${cols}
// One literal: concatenating thousands of short strings overflows parsers.
export const GEOID_BASE64 = '${base64}'
`
)
console.info(`Wrote ${out} (${base64.length} base64 chars)`)
